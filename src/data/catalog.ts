/**
 * Generates a realistic 64-bar audio transient peak profile (intro, drum drop, breakdown, hook)
 * instead of a smooth Math.sin sine wave.
 */
function makeWaveform(seed: number): number[] {
  const bars: number[] = [];
  let s = seed * 9301 + 49297;
  const nextRand = () => {
    s = (s * 9301 + 49297) % 233280;
    return s / 233280;
  };

  for (let i = 0; i < 64; i++) {
    const isIntro = i < 7;
    const isBreak = i >= 28 && i <= 33;
    const isOutro = i > 57;
    const isTransient = i % 4 === 0 || i % 7 === 0;

    let base = nextRand() * 0.55 + 0.25;
    if (isTransient) base += 0.26;
    if (isIntro) base *= 0.42;
    if (isBreak) base *= 0.35;
    if (isOutro) base *= 0.48;

    bars.push(Math.max(0.12, Math.min(0.98, Number(base.toFixed(2)))));
  }
  return bars;
}

